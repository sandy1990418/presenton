    async def save_layouts(self, layouts_data: List[Dict]) -> tuple[int, str]:
        """
        Save presentation layouts to database.
        
        Args:
            layouts_data: List of layout data dictionaries
            
        Returns:
            Tuple of (saved_count, message)
        """
        self.log_request_start("save_layouts", layout_count=len(layouts_data))
        
        try:
            saved_count = 0
            
            for layout_data in layouts_data:
                # Validate required fields
                self.validate_string_length(layout_data.get("presentation_id", ""), "presentation_id", min_length=1)
                self.validate_string_length(layout_data.get("layout_id", ""), "layout_id", min_length=1)
                self.validate_string_length(layout_data.get("layout_name", ""), "layout_name", min_length=1)
                self.validate_string_length(layout_data.get("layout_code", ""), "layout_code", min_length=1)
                
                # Check if layout already exists
                existing = await self.sql_session.get(
                    PresentationLayoutCodeModel,
                    (layout_data["presentation_id"], layout_data["layout_id"])
                )
                
                if existing:
                    # Update existing layout
                    existing.layout_name = layout_data["layout_name"]
                    existing.layout_code = layout_data["layout_code"]
                    existing.fonts = layout_data.get("fonts")
                    self.logger.debug("Updated existing layout", 
                                    presentation_id=layout_data["presentation_id"],
                                    layout_id=layout_data["layout_id"])
                else:
                    # Create new layout
                    new_layout = PresentationLayoutCodeModel(
                        presentation_id=layout_data["presentation_id"],
                        layout_id=layout_data["layout_id"],
                        layout_name=layout_data["layout_name"],
                        layout_code=layout_data["layout_code"],
                        fonts=layout_data.get("fonts")
                    )
                    await self.safe_add(new_layout)
                    self.logger.debug("Created new layout", 
                                    presentation_id=layout_data["presentation_id"],
                                    layout_id=layout_data["layout_id"])
                
                saved_count += 1
            
            await self.safe_commit()
            
            self.log_request_success("save_layouts", saved_count=saved_count)
            return saved_count, f"Successfully saved {saved_count} layouts"
            
        except HTTPException:
            await self.sql_session.rollback()
            raise
        except Exception as e:
            await self.sql_session.rollback()
            self.log_request_error("save_layouts", e, layout_count=len(layouts_data))
            raise HTTPException(
                status_code=500,
                detail=f"Error saving layouts: {str(e)}"
            )

    async def get_layouts(self, presentation_id: str) -> tuple[List[Dict], Optional[dict], Optional[List[str]]]:
        """
        Retrieve layouts for a presentation.
        
        Args:
            presentation_id: ID of the presentation
            
        Returns:
            Tuple of (layouts, template, fonts)
        """
        self.log_request_start("get_layouts", presentation_id=presentation_id)
        
        try:
            self.validate_string_length(presentation_id, "presentation_id", min_length=1)
            
            # Query layouts for the presentation
            result = await self.sql_session.execute(
                select(PresentationLayoutCodeModel)
                .where(PresentationLayoutCodeModel.presentation_id == presentation_id)
            )
            layout_models = result.scalars().all()
            
            layouts = []
            template = None
            fonts = None
            
            for layout_model in layout_models:
                layout_dict = {
                    "presentation_id": layout_model.presentation_id,
                    "layout_id": layout_model.layout_id,
                    "layout_name": layout_model.layout_name,
                    "layout_code": layout_model.layout_code
                }
                if layout_model.fonts:
                    layout_dict["fonts"] = layout_model.fonts
                layouts.append(layout_dict)
            
            # Get template info if available
            template_result = await self.sql_session.execute(
                select(TemplateModel).where(TemplateModel.id == presentation_id)
            )
            template_model = template_result.scalar_one_or_none()
            
            if template_model:
                template = {
                    "id": template_model.id,
                    "name": template_model.name,
                    "description": template_model.description,
                    "created_at": template_model.created_at
                }
            
            self.log_request_success("get_layouts", 
                                   presentation_id=presentation_id,
                                   layout_count=len(layouts))
            
            return layouts, template, fonts
            
        except HTTPException:
            raise
        except Exception as e:
            self.log_request_error("get_layouts", e, presentation_id=presentation_id)
            raise HTTPException(
                status_code=500,
                detail=f"Error retrieving layouts: {str(e)}"
            )

    async def get_presentations_summary(self) -> tuple[List[Dict], int, int]:
        """
        Get summary of all presentations with layout counts.
        
        Returns:
            Tuple of (presentations, total_presentations, total_layouts)
        """
        self.log_request_start("get_presentations_summary")
        
        try:
            # Query layout counts per presentation
            result = await self.sql_session.execute(
                select(
                    PresentationLayoutCodeModel.presentation_id,
                    func.count(PresentationLayoutCodeModel.layout_id).label("layout_count"),
                    func.max(PresentationLayoutCodeModel.updated_at).label("last_updated_at")
                )
                .group_by(PresentationLayoutCodeModel.presentation_id)
            )
            presentation_summaries = result.all()
            
            presentations = []
            total_layouts = 0
            
            for summary in presentation_summaries:
                presentation_id = summary.presentation_id
                layout_count = summary.layout_count
                last_updated_at = summary.last_updated_at
                total_layouts += layout_count
                
                # Get template info if available
                template_result = await self.sql_session.execute(
                    select(TemplateModel).where(TemplateModel.id == presentation_id)
                )
                template_model = template_result.scalar_one_or_none()
                
                template_info = None
                if template_model:
                    template_info = {
                        "id": template_model.id,
                        "name": template_model.name,
                        "description": template_model.description,
                        "created_at": template_model.created_at
                    }
                
                presentations.append({
                    "presentation_id": presentation_id,
                    "layout_count": layout_count,
                    "last_updated_at": last_updated_at,
                    "template": template_info
                })
            
            total_presentations = len(presentations)
            
            self.log_request_success("get_presentations_summary", 
                                   total_presentations=total_presentations,
                                   total_layouts=total_layouts)
            
            return presentations, total_presentations, total_layouts
            
        except Exception as e:
            self.log_request_error("get_presentations_summary", e)
            raise HTTPException(
                status_code=500,
                detail=f"Error retrieving presentations summary: {str(e)}"
            )

    async def create_template(self, template_id: str, name: str, description: Optional[str] = None) -> dict:
        """
        Create or update a template.
        
        Args:
            template_id: ID of the template
            name: Name of the template
            description: Optional description
            
        Returns:
            Template dictionary
        """
        self.log_request_start("create_template", template_id=template_id, name=name)
        
        try:
            self.validate_string_length(template_id, "template_id", min_length=1)
            self.validate_string_length(name, "name", min_length=1)
            
            # Check if template exists
            existing = await self.sql_session.get(TemplateModel, template_id)
            
            if existing:
                # Update existing template
                existing.name = name
                existing.description = description
                self.logger.debug("Updated existing template", template_id=template_id)
            else:
                # Create new template
                new_template = TemplateModel(
                    id=template_id, 
                    name=name, 
                    description=description
                )
                await self.safe_add(new_template)
                self.logger.debug("Created new template", template_id=template_id)
            
            await self.safe_commit()
            
            # Read back the template
            template = await self.sql_session.get(TemplateModel, template_id)
            template_dict = {
                "id": template.id,
                "name": template.name,
                "description": template.description,
                "created_at": template.created_at,
            }
            
            self.log_request_success("create_template", template_id=template_id)
            return template_dict
            
        except HTTPException:
            await self.sql_session.rollback()
            raise
        except Exception as e:
            await self.sql_session.rollback()
            self.log_request_error("create_template", e, template_id=template_id)
            raise HTTPException(
                status_code=500,
                detail=f"Error creating template: {str(e)}"
            )

