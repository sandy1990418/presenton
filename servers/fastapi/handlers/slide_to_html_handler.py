    async def generate_html_from_slide(
        self, 
        base64_image: str, 
        media_type: str, 
        xml_content: str, 
        api_key: str, 
        fonts: Optional[List[str]] = None
    ) -> str:
        """
        Generate HTML content from slide image and XML using OpenAI GPT-5.
        
        Args:
            base64_image: Base64 encoded image data
            media_type: MIME type of the image
            xml_content: OXML content as text
            api_key: OpenAI API key
            fonts: Optional list of normalized root font families
            
        Returns:
            Generated HTML content as string
        """
        self.log_external_service_call("OpenAI", "generate_html_from_slide")
        
        try:
            client = OpenAI(api_key=api_key)

            # Compose input for Responses API
            data_url = f"data:{media_type};base64,{base64_image}"
            fonts_text = f"\nFONTS (Normalized root families used in this slide, use where it is required): {', '.join(fonts)}" if fonts else ""
            user_text = f"OXML: \n\n{fonts_text}"
            
            # Import the system prompt here to avoid circular imports
            from api.v1.ppt.endpoints.prompts import GENERATE_HTML_SYSTEM_PROMPT
            
            input_payload = [
                {"role": "system", "content": GENERATE_HTML_SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": [
                        {"type": "input_image", "image_url": data_url},
                        {"type": "input_text", "text": user_text},
                    ],
                },
            ]

            self.logger.debug("Making OpenAI API request for HTML generation")
            response = client.responses.create(
                model="gpt-5",
                input=input_payload,
                reasoning={"effort": "high"},
                text={"verbosity": "low"},
            )

            html_content = getattr(response, "output_text", None) or getattr(response, "text", None) or ""
            
            self.logger.info("Generated HTML content", content_length=len(html_content))
            
            if not html_content:
                self.log_external_service_error("OpenAI", "generate_html", "No HTML content generated")
                raise HTTPException(
                    status_code=500,
                    detail="No HTML content generated by OpenAI GPT-5"
                )
            
            return html_content
            
        except APIError as e:
            self.log_external_service_error("OpenAI", "generate_html", str(e))
            raise HTTPException(
                status_code=500,
                detail=f"OpenAI API error during HTML generation: {str(e)}"
            )
        except Exception as e:
            error_msg = str(e)
            self.logger.exception("Failed to generate HTML from slide", error_type=type(e).__name__)
            
            if "timeout" in error_msg.lower():
                raise HTTPException(
                    status_code=408,
                    detail=f"OpenAI API timeout during HTML generation: {error_msg}"
                )
            elif "connection" in error_msg.lower():
                raise HTTPException(
                    status_code=503,
                    detail=f"OpenAI API connection error during HTML generation: {error_msg}"
                )
            else:
                raise HTTPException(
                    status_code=500,
                    detail=f"OpenAI API error during HTML generation: {error_msg}"
                )

    async def generate_react_component_from_html(
        self, 
        html_content: str, 
        api_key: str, 
        image_base64: Optional[str] = None, 
        media_type: Optional[str] = None
    ) -> str:
        """
        Convert HTML content to TSX React component using OpenAI GPT-5.
        
        Args:
            html_content: Generated HTML content
            api_key: OpenAI API key
            image_base64: Optional base64 image data
            media_type: Optional media type for image
            
        Returns:
            Generated TSX React component code as string
        """
        self.log_external_service_call("OpenAI", "generate_react_component")
        
        try:
            client = OpenAI(api_key=api_key)

            # Build payload with optional image
            content_parts = [{"type": "input_text", "text": f"HTML INPUT:\n{html_content}"}]
            if image_base64 and media_type:
                data_url = f"data:{media_type};base64,{image_base64}"
                content_parts.insert(0, {"type": "input_image", "image_url": data_url})

            from api.v1.ppt.endpoints.prompts import HTML_TO_REACT_SYSTEM_PROMPT
            
            input_payload = [
                {"role": "system", "content": HTML_TO_REACT_SYSTEM_PROMPT},
                {"role": "user", "content": content_parts},
            ]

            response = client.responses.create(
                model="gpt-5",
                input=input_payload,
                reasoning={"effort": "minimal"},
                text={"verbosity": "low"},
            )

            react_content = getattr(response, "output_text", None) or getattr(response, "text", None) or ""
            
            self.logger.info("Generated React content", content_length=len(react_content))
            
            if not react_content:
                self.log_external_service_error("OpenAI", "generate_react", "No React component generated")
                raise HTTPException(
                    status_code=500,
                    detail="No React component generated by OpenAI GPT-5"
                )
            
            # Clean up the generated content
            react_content = react_content.replace("```tsx", "").replace("```", "").replace("typescript", "").replace("javascript", "")

            # Filter out import/export lines
            filtered_lines = []
            for line in react_content.split('\n'):
                stripped_line = line.strip()
                if not (stripped_line.startswith('import ') or stripped_line.startswith('export ')):
                    filtered_lines.append(line)
            
            filtered_react_content = '\n'.join(filtered_lines)
            self.logger.debug("Filtered React content", filtered_length=len(filtered_react_content))
            
            return filtered_react_content
            
        except APIError as e:
            self.log_external_service_error("OpenAI", "generate_react", str(e))
            raise HTTPException(
                status_code=500,
                detail=f"OpenAI API error during React generation: {str(e)}"
            )
        except Exception as e:
            error_msg = str(e)
            self.logger.exception("Failed to generate React component", error_type=type(e).__name__)
            
            if "timeout" in error_msg.lower():
                raise HTTPException(
                    status_code=408,
                    detail=f"OpenAI API timeout during React generation: {error_msg}"
                )
            elif "connection" in error_msg.lower():
                raise HTTPException(
                    status_code=503,
                    detail=f"OpenAI API connection error during React generation: {error_msg}"
                )
            else:
                raise HTTPException(
                    status_code=500,
                    detail=f"OpenAI API error during React generation: {error_msg}"
                )

