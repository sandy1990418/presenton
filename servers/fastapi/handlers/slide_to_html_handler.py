    async def convert_slide_to_html(self, image_path: str, xml_content: str, fonts: Optional[List[str]] = None) -> str:
        """
        Convert a slide image and XML to HTML.
        
        Args:
            image_path: Path to the slide image
            xml_content: OXML content
            fonts: Optional list of fonts
            
        Returns:
            Generated HTML content
        """
        self.log_request_start("convert_slide_to_html", image_path=image_path)
        
        try:
            # Get OpenAI API key
            api_key = os.getenv("OPENAI_API_KEY")
            if not api_key:
                self.log_validation_error("api_key", "missing", "OPENAI_API_KEY environment variable not set")
                raise HTTPException(
                    status_code=500, 
                    detail="OPENAI_API_KEY environment variable not set"
                )
            
            # Resolve image path to actual file system path
            if image_path.startswith("/app_data/images/"):
                relative_path = image_path[len("/app_data/images/"):]
                actual_image_path = os.path.join(get_images_directory(), relative_path)
            elif image_path.startswith("/static/"):
                relative_path = image_path[len("/static/"):]
                actual_image_path = os.path.join("static", relative_path)
            else:
                if os.path.isabs(image_path):
                    actual_image_path = image_path
                else:
                    actual_image_path = os.path.join(get_images_directory(), image_path)
            
            # Check if image file exists
            if not os.path.exists(actual_image_path):
                self.log_validation_error("image_file", "not_found", f"Image file not found: {image_path}")
                raise HTTPException(
                    status_code=404,
                    detail=f"Image file not found: {image_path}"
                )
            
            # Read and encode image
            with open(actual_image_path, "rb") as image_file:
                image_content = image_file.read()
            base64_image = base64.b64encode(image_content).decode('utf-8')
            
            # Determine media type
            file_extension = os.path.splitext(actual_image_path)[1].lower()
            media_type_map = {
                '.png': 'image/png',
                '.jpg': 'image/jpeg',
                '.jpeg': 'image/jpeg',
                '.gif': 'image/gif',
                '.webp': 'image/webp'
            }
            media_type = media_type_map.get(file_extension, 'image/png')
            
            # Generate HTML
            html_content = await self.generate_html_from_slide(
                base64_image=base64_image,
                media_type=media_type,
                xml_content=xml_content,
                api_key=api_key,
                fonts=fonts,
            )
            
            # Clean up HTML
            html_content = html_content.replace("```html", "").replace("```", "")
            
            self.log_request_success("convert_slide_to_html", html_length=len(html_content))
            return html_content
            
        except HTTPException:
            raise
        except Exception as e:
            self.log_request_error("convert_slide_to_html", e, image_path=image_path)
            raise HTTPException(
                status_code=500,
                detail=f"Error processing slide to HTML: {str(e)}"
            )

